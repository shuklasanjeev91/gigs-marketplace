// ── Generator ─────────────────────────────────────────────────────────────────
function generateCategoryGigs(
  category: string,
  spec: CategorySpec,
  count = 100,
): GigCardData[] {
  return Array.from({ length: count }, (_, i) => {
    const seller = MOCK_SELLERS[i % MOCK_SELLERS.length];
    return {
      id: `mock-${category}-${i + 1}`,
      title: spec.titles[i % spec.titles.length],
      category,
      price: spec.prices[i % spec.prices.length],
      delivery_days: spec.deliveries[i % spec.deliveries.length],
      tags: spec.tagSets[i % spec.tagSets.length],
      image_url: spec.images[i % spec.images.length],
      seller_id: seller.id,
      seller,
      avg_rating: parseFloat((4.0 + ((i * 7 + 3) % 11) * 0.1).toFixed(1)),
      review_count: 10 + ((i * 113 + 7) % 2500),
    };
  });
}

// ── Export ────────────────────────────────────────────────────────────────────
export const mockGigs: GigCardData[] = Object.entries(CATEGORY_SPECS).flatMap(
  ([category, spec]) => generateCategoryGigs(category, spec),
);

// ── Filter ────────────────────────────────────────────────────────────────────
export function filterMockGigs(
  gigs: GigCardData[],
  options: {
    query?: string;
    category?: string;
    priceMin?: number;
    priceMax?: number;
    deliveryDays?: number | null;
    sellerLevel?: string | null;
    sellerId?: string;
    limit?: number;
    sortBy?: "recommended" | "price-low" | "price-high" | "rating" | "reviews";
  }
): GigCardData[] {
  let result = [...gigs];

  if (options.category && options.category !== "all") {
    result = result.filter((g) => g.category === options.category);
  }
  if (options.priceMin !== undefined) {
    result = result.filter((g) => g.price >= options.priceMin!);
  }
  if (options.priceMax !== undefined) {
    result = result.filter((g) => g.price <= options.priceMax!);
  }
  if (options.deliveryDays) {
    result = result.filter((g) => g.delivery_days <= options.deliveryDays!);
  }
  if (options.query) {
    const q = options.query.toLowerCase();
    result = result.filter(
      (g) =>
        g.title.toLowerCase().includes(q) ||
        (g.tags ?? []).some((t) => t.toLowerCase().includes(q))
    );
  }
  if (options.sellerLevel && options.sellerLevel !== "all") {
    result = result.filter(
      (g) => g.seller?.seller_level === options.sellerLevel
    );
  }
  if (options.sellerId) {
    result = result.filter((g) => g.seller_id === options.sellerId);
  }

  if (options.sortBy === "price-low") {
    result = result.sort((a, b) => a.price - b.price);
  } else if (options.sortBy === "price-high") {
    result = result.sort((a, b) => b.price - a.price);
  } else if (options.sortBy === "rating") {
    result = result.sort((a, b) => (b.avg_rating ?? 0) - (a.avg_rating ?? 0));
  } else if (options.sortBy === "reviews") {
    result = result.sort((a, b) => (b.review_count ?? 0) - (a.review_count ?? 0));
  }

  if (options.limit) {
    result = result.slice(0, options.limit);
  }

  return result;
}
